#!/usr/bin/env python3
"""Writes loudness_data.h: low and high shelves that turn the ISO 226:2003 equal-loudness contour at
each listening level into the 80-phon one, fitted on the analog RBJ shelf so any sample rate can use them.
  gen_loudness.py OUT.h"""
import math, sys

F = [20, 25, 31.5, 40, 50, 63, 80, 100, 125, 160, 200, 250, 315, 400, 500, 630, 800, 1000, 1250, 1600, 2000,
     2500, 3150, 4000, 5000, 6300, 8000, 10000, 12500]
AF = [0.532, 0.506, 0.480, 0.455, 0.432, 0.409, 0.387, 0.367, 0.349, 0.330, 0.315, 0.301, 0.288, 0.276, 0.267, 0.259,
      0.253, 0.250, 0.246, 0.244, 0.243, 0.243, 0.243, 0.242, 0.242, 0.245, 0.254, 0.271, 0.301]
LU = [-31.6, -27.2, -23.0, -19.1, -15.9, -13.0, -10.3, -8.1, -6.2, -4.5, -3.1, -2.0, -1.1, -0.4, 0.0, 0.3, 0.5, 0.0,
      -2.7, -4.1, -1.0, 1.7, 2.5, 1.2, -2.1, -7.1, -11.2, -10.7, -3.1]
TF = [78.5, 68.7, 59.5, 51.1, 44.0, 37.5, 31.5, 26.5, 22.1, 17.9, 14.4, 11.4, 8.6, 6.2, 4.4, 3.0, 2.2, 2.4, 3.5, 1.7,
      -1.3, -4.2, -6.0, -5.4, -1.5, 6.0, 12.6, 13.9, 12.3]
REF, MAX_BOOST, MAX_TREBLE = 80, 12.0, 6.0

def contour(phon):
    out = []
    for af, lu, tf in zip(AF, LU, TF):
        a = 4.47e-3 * (10 ** (0.025 * phon) - 1.15) + (0.4 * 10 ** ((tf + lu) / 10 - 9)) ** af
        out.append(10 / af * math.log10(a) - lu + 94)
    return out

def shelf_db(f, fc, db, high, S=0.7):
    """analog RBJ shelf magnitude in dB"""
    A = 10 ** (db / 40); w = f / fc
    al = math.sqrt((A + 1 / A) * (1 / S - 1) + 2)          # 2*alpha/sin(w0) of the cookbook, analog form
    s = 1j * w
    if not high: h = A * (s * s + math.sqrt(A) * al * s + A) / (A * s * s + math.sqrt(A) * al * s + 1)
    else: h = A * (A * s * s + math.sqrt(A) * al * s + 1) / (s * s + math.sqrt(A) * al * s + A)
    return 20 * math.log10(abs(h))

def fit(target, freqs, high):
    best = None
    fcs = [40 * 1.05 ** k for k in range(80)] if not high else [6000 * 1.04 ** k for k in range(18)]   # corner 6-12 kHz: below Nyquist at 32 kHz and up
    for fc in fcs:
        for g10 in range(0, int((MAX_BOOST if not high else MAX_TREBLE) * 4) + 1):
            g = g10 / 4
            e = sum((shelf_db(f, fc, g, high) - t) ** 2 for f, t in zip(freqs, target))
            if best is None or e < best[0]: best = (e, fc, g)
    return best

ref = contour(REF)
rows = []
for phon in range(20, REF + 1, 5):
    c = contour(phon)
    d = [min((c[i] - phon) - (ref[i] - REF), MAX_BOOST) for i in range(len(F))]
    lo = [(f, t) for f, t in zip(F, d) if 31.5 <= f <= 1000]
    hi = [(f, t) for f, t in zip(F, d) if 1000 <= f]
    el, lfc, lg = fit([t for f, t in lo], [f for f, t in lo], False)
    eh, hfc, hg = fit([max(t, 0) for f, t in hi], [f for f, t in hi], True)
    rows.append((phon, lfc, lg, hfc, hg, math.sqrt(el / len(lo)), math.sqrt(eh / len(hi))))
with open(sys.argv[1], 'w') as f:
    f.write('/* generated by host/gen_loudness.py from the ISO 226:2003 contours; do not edit */\n')
    f.write('/* listening level (phon), low shelf (Hz, dB), high shelf (Hz, dB); S 0.7; flat at %d phon */\n' % REF)
    f.write('static const float loud_tab[%d][5] = {\n' % len(rows))
    for r in rows: f.write('    { %d, %.1f, %.2f, %.1f, %.2f },   /* rms error %.2f / %.2f dB */\n' % r)
    f.write('};\n')
for r in rows: print('%3d phon: low %6.1f Hz %+5.2f dB   high %7.1f Hz %+5.2f dB   err %.2f %.2f' % r)
