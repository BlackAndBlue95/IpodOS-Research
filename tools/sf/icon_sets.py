#!/usr/bin/env python3
"""Resources/Icons/{Classic,Modern}.bin and their table runtime/sficons_data.h ('FICN', table id,
kind, size, then each icon padded to 4 bytes). gen_sficons.py calls write().

    icon_sets.py OSOS.dec SFICONS_DATA.h OUTDIR     # from a header that still holds sf_raw"""
import os, re, struct, sys, zlib

PKG, PKG_DATA = 0x08400258, 0x08417928
HDR, DRAM_DELTA = 0x800, 0x07ff5128


def stock_index(osos):
    img = open(osos, 'rb').read()
    u = lambda a: struct.unpack_from('<I', img, HDR + a - DRAM_DELTA)[0]
    for i in range(u(PKG + 8)):
        t = PKG + 12 + 16 * i
        if u(t) == 0x424d6170:                           # 'BMap'
            ix = PKG + u(t + 12)
            return img, {u(ix + 12 * k): (u(ix + 12 * k + 4), u(ix + 12 * k + 8)) for k in range(u(t + 4))}
    raise SystemExit('no BMap index')


def pack(slots, sizes):
    """modern offsets: each icon into the bytes the Classic icons of the table occupy (best fit,
    largest first, 4-byte aligned)"""
    al = lambda x: (x + 3) & ~3
    ext = []
    for o, s in sorted(slots.values()):
        if ext and o <= ext[-1][1] + 3: ext[-1][1] = max(ext[-1][1], o + s)
        else: ext.append([o, o + s])
    free = [[al(a), b] for a, b in ext]
    out = {}
    for sz, pid in sorted(((s, p) for p, s in sizes.items()), reverse=True):
        fit = [f for f in free if f[1] - f[0] >= sz]
        assert fit, 'icon %#x (%d bytes) does not fit the Classic set' % (pid, sz)
        f = min(fit, key=lambda f: f[1] - f[0])
        out[pid] = f[0]; f[0] = al(f[0] + sz)
    return out


def write(osos, tab, data, accent, header, outdir):
    """tab: [(id, name)], data: {id: Modern bytes}"""
    img, ix = stock_index(osos)
    slots = {pid: ix[pid] for pid, _ in tab}
    classic = {pid: img[HDR + PKG_DATA + o - DRAM_DELTA:HDR + PKG_DATA + o - DRAM_DELTA + s] for pid, (o, s) in slots.items()}
    moff = pack(slots, {pid: len(data[pid]) for pid, _ in tab})
    rows = [(pid, len(data[pid]), slots[pid][1], moff[pid], n) for pid, n in tab]
    tid = zlib.crc32(b''.join(struct.pack('<4I', *r[:4]) for r in rows))
    os.makedirs(outdir, exist_ok=True)
    for kind, name, src in ((0, 'Classic.bin', classic), (1, 'Modern.bin', data)):
        body = b''.join(src[pid] + b'\0' * (-len(src[pid]) & 3) for pid, _ in tab)
        open(os.path.join(outdir, name), 'wb').write(struct.pack('<4sIII', b'FICN', tid, kind, len(body)) + body)
    with open(header, 'w') as f:
        f.write('/* generated by tools/sf/icon_sets.py: Apple SF Symbols, personal use, do not commit */\n')
        f.write('#define SF_N %d\n#define SF_SETS 0x%08x   /* Resources/Icons/{Classic,Modern}.bin made with this table */\n' % (len(rows), tid))
        f.write('/* id, Modern size, Classic size, Modern offset from PKG_DATA */\nstatic const uint32_t sf_tab[SF_N][4] = {\n')
        for pid, ms, cs, mo, n in rows: f.write('    { 0x%08x, %d, %d, 0x%x }, /* %s */\n' % (pid, ms, cs, mo, n))
        f.write('};\n/* recoloured to the accent at boot */\nstatic const uint32_t sf_accent[%d] = { %s };\n' % (max(1, len(accent)), ', '.join('0x%08x' % v for v in sorted(accent)) or '0'))
        f.write('#define SF_NACCENT %d\n' % len(accent))
    print('icon sets: %d icons, Classic %d bytes, Modern %d bytes, table %08x' % (len(rows), sum(r[2] for r in rows), sum(r[1] for r in rows), tid))


if __name__ == '__main__':
    osos, old, outdir = sys.argv[1:4]
    t = open(old).read()
    rows = [(int(a, 16), int(b), int(c), n) for a, b, c, _, n in re.findall(r'\{ (0x[0-9a-f]+), (\d+), (\d+), (\d+) \}, /\* (\S+) \*/', t)]
    raw = bytes(int(v) for v in re.findall(r'\d+', t.split('sf_raw[')[1].split('{', 1)[1].split('}')[0]))
    accent = [int(v, 16) for v in re.findall(r'0x[0-9a-f]+', t.split('sf_accent[')[1].split('{', 1)[1].split('}')[0])]
    write(osos, [(pid, n) for pid, _, _, n in rows], {pid: raw[o:o + s] for pid, s, o, _ in rows}, accent,
          os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'runtime', 'sficons_data.h'), outdir)
